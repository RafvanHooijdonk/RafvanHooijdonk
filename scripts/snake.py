"""Own contribution snake: eats every day with contributions and grows with each bite.

Replaces Platane/snk so length, route and speed are ours. Writes dist/github-snake.svg
and dist/github-snake-dark.svg, which the snake workflow publishes on the output branch.
Animation is plain SMIL, so it plays inside an <img> on GitHub.
"""
import json, os, sys, urllib.request
from collections import deque

TOKEN = os.environ["GH_TOKEN"]
OUT = sys.argv[1] if len(sys.argv) > 1 else "dist"

CELL, DOT, RADIUS = 16, 12, 4
START_LEN, MAX_LEN = 4, 24          # grows one segment per bite, up to MAX_LEN
SECONDS_PER_STEP = 0.09             # speed of the snake, one grid cell per step
THEMES = {
    "github-snake.svg": dict(dots=["#e2e8f0", "#bae6fd", "#38bdf8", "#0ea5e9", "#8b5cf6"], border="#0f172a14",
                             head="#16a34a", tail="#86efac", bar="#bae6fd", bar_done="#38bdf8"),
    "github-snake-dark.svg": dict(dots=["#1e293b", "#0c4a6e", "#0369a1", "#0ea5e9", "#8b5cf6"], border="#ffffff14",
                                  head="#22c55e", tail="#14532d", bar="#0c4a6e", bar_done="#0ea5e9"),
}
LEVEL = {"NONE": 0, "FIRST_QUARTILE": 1, "SECOND_QUARTILE": 2, "THIRD_QUARTILE": 3, "FOURTH_QUARTILE": 4}

QUERY = """{ viewer { contributionsCollection { contributionCalendar { weeks { contributionDays {
  contributionLevel weekday } } } } } }"""
req = urllib.request.Request("https://api.github.com/graphql", data=json.dumps({"query": QUERY}).encode(),
                             headers={"Authorization": f"bearer {TOKEN}", "Content-Type": "application/json"})
with urllib.request.urlopen(req, timeout=30) as r:
    weeks = json.load(r)["data"]["viewer"]["contributionsCollection"]["contributionCalendar"]["weeks"]

grid = {}  # (x, y) -> level, for every day in the calendar
for x, w in enumerate(weeks):
    for d in w["contributionDays"]:
        grid[(x, d["weekday"])] = LEVEL[d["contributionLevel"]]
W, H = len(weeks), 7

# ---- route: from above the grid to the nearest uneaten day, again and again ----
def neighbours(p):
    x, y = p
    for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
        if -1 <= nx <= W and -2 <= ny <= H:  # one lane around the grid to turn in
            yield (nx, ny)

def path_to_nearest(start, targets):
    prev, q = {start: None}, deque([start])
    while q:
        p = q.popleft()
        if p in targets and p != start:
            out = []
            while p != start:
                out.append(p)
                p = prev[p]
            return out[::-1]
        for n in neighbours(p):
            if n not in prev:
                prev[n] = p
                q.append(n)
    return []

head = (0, -2)
route = [head]
targets = {p for p, lv in grid.items() if lv > 0}
eaten_at = {}  # cell -> step it was eaten
while targets:
    step_path = path_to_nearest(route[-1], targets)
    route += step_path
    cell = step_path[-1]
    eaten_at[cell] = len(route) - 1
    targets.discard(cell)
# leave the stage at the top right, then the round starts over
while route[-1] != (W, -2):
    x, y = route[-1]
    route.append((x + 1, y) if x < W else (x, y - 1))
for _ in range(MAX_LEN + 2):
    route.append((route[-1][0] + 1, -2))

steps = len(route)
dur = round(steps * SECONDS_PER_STEP, 2)
bites = sorted(eaten_at.values())

def length_at(t):
    return min(MAX_LEN, START_LEN + sum(1 for b in bites if b <= t))

def kt(t):
    return f"{t / (steps - 1):.4f}"

def svg(theme):
    th = THEMES[theme]
    o = [f'<svg viewBox="-16 -40 {W * CELL + 32} {H * CELL + 72}" width="{W * CELL + 32}" height="{H * CELL + 72}" '
         'xmlns="http://www.w3.org/2000/svg"><desc>Contribution snake, generated by scripts/snake.py</desc>']
    off = (CELL - DOT) / 2
    # cells: coloured until eaten, then empty for the rest of the round
    for (x, y), lv in sorted(grid.items()):
        px, py = x * CELL + off, y * CELL + off
        base = f'<rect x="{px}" y="{py}" width="{DOT}" height="{DOT}" rx="{RADIUS}" stroke="{th["border"]}" stroke-width="1"'
        if lv and (x, y) in eaten_at:
            o.append(f'{base} fill="{th["dots"][lv]}"><animate attributeName="fill" calcMode="discrete" '
                     f'values="{th["dots"][lv]};{th["dots"][0]};{th["dots"][lv]}" keyTimes="0;{kt(eaten_at[(x, y)])};1" '
                     f'dur="{dur}s" repeatCount="indefinite"/></rect>')
        else:
            o.append(f'{base} fill="{th["dots"][0]}"/>')
    # progress bar: fills as days get eaten
    by = H * CELL + 14
    o.append(f'<rect x="0" y="{by}" width="{W * CELL}" height="6" rx="3" fill="{th["bar"]}"/>')
    o.append(f'<rect x="0" y="{by}" width="{W * CELL}" height="6" rx="3" fill="{th["bar_done"]}">'
             f'<animate attributeName="width" values="0;{W * CELL};{W * CELL}" keyTimes="0;{kt(bites[-1] if bites else 1)};1" '
             f'dur="{dur}s" repeatCount="indefinite"/></rect>')
    # snake: segment i follows the head i steps later, and shows once the snake is that long
    def mix(a, b, f):
        a, b = [int(a[i:i + 2], 16) for i in (1, 3, 5)], [int(b[i:i + 2], 16) for i in (1, 3, 5)]
        return "#" + "".join(f"{round(x + (y - x) * f):02x}" for x, y in zip(a, b))
    for i in reversed(range(MAX_LEN)):
        size = max(6, 13 - i * 0.3)
        o2 = (CELL - size) / 2
        xs = ";".join(str(route[max(0, t - i)][0] * CELL + o2) for t in range(steps))
        ys = ";".join(str(route[max(0, t - i)][1] * CELL + o2) for t in range(steps))
        appear = next((t for t in range(steps) if length_at(t) > i), steps - 1)
        vis = (f'<animate attributeName="opacity" calcMode="discrete" values="0;1;0" keyTimes="0;{kt(appear)};1" '
               f'dur="{dur}s" repeatCount="indefinite"/>') if i >= START_LEN else ""
        o.append(f'<rect width="{size:.1f}" height="{size:.1f}" rx="{size / 2.6:.1f}" fill="{mix(th["head"], th["tail"], i / MAX_LEN)}" '
                 f'opacity="{1 if i < START_LEN else 0}">'
                 f'<animate attributeName="x" values="{xs}" dur="{dur}s" repeatCount="indefinite"/>'
                 f'<animate attributeName="y" values="{ys}" dur="{dur}s" repeatCount="indefinite"/>{vis}</rect>')
    o.append("</svg>")
    return "".join(o)

os.makedirs(OUT, exist_ok=True)
for name in THEMES:
    with open(os.path.join(OUT, name), "w") as f:
        f.write(svg(name))
print(f"{len(eaten_at)} days eaten in {steps} steps, max length {MAX_LEN}, files in {OUT}/")
